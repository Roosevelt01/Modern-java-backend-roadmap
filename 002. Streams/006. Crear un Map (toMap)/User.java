package Modern_java_backend_roadmap.Stream.Ejercicio_6_Crear_toMap;

public class User {
    private int id;
    private String name;

    public User(int id, String name) {
        this.id = id;
        this.name = name;
    }

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }
}